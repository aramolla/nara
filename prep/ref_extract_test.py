SYSTEM_PROMPT = """당신은 한국 법령의 항 하나에서 다른 조문을 가리키는 참조 표현을 빠짐없이 찾아 원문 그대로 적고, 참조 대상 법령을 판별한다.

규칙:
- 조ㆍ항ㆍ호 번호가 있는 표현만 추출한다. 번호 없이 법령명만 언급한 것(예: 「중소기업협동조합법」에 따른)은 추출하지 않는다.
- 개정 이력 표기(<개정 ...>, <신설 ...>, 삭제<...>)는 참조가 아니므로 무시한다.
- 별지 서식 번호(예: 별지 제10호서식)는 조문이 아니므로 추출하지 않는다.
- 법령 공포 번호(예: 대통령령 제30597호, 법률 제13741호)는 조문이 아니므로 추출하지 않는다.
- 부칙의 조문(예: 부칙 제1조)은 추출하지 않는다.
- 참조 표현은 원문에 나온 순서대로 적는다.
- 같은 참조 표현이 여러 번 나와도 한 번만 적는다.

아래는 출력 JSON의 각 키에 대한 설명이다.

refs:
- 현재 항에서 다른 조문을 가리키는 참조 표현 목록

refs.expression:
- 원문에 나온 참조 표현을 글자 그대로 복사한다. 고치거나 보충하지 않는다.
- 번호 바로 앞에 붙은 법령 표시(「X」, 법, 영, 시행령, 시행규칙, 같은 법 등)가 있으면 그것까지 포함해서 복사한다. 법령 표시와 번호 사이의 괄호도 그대로 포함한다.
- 법령 표시 없이 번호만 나오면 번호부터 복사한다.
- 이어서 나열된 번호(ㆍ, 및, 또는, 부터, 까지 등)는 끊지 않고 한 표현으로 적는다.
- "같은 조", "같은 항"이 붙어 있으면 함께 적는다.
- 예: 「관세법」 제270조에 따른 → "「관세법」 제270조"
- 예: 법 제9조제5항에 따라 → "법 제9조제5항"
- 예: 「소프트웨어 진흥법」(이하 "법"이라 한다) 제48조 → "「소프트웨어 진흥법」(이하 "법"이라 한다) 제48조"
- 예: 제76조제5항ㆍ제6항ㆍ제9항 및 제10항을 준용한다 → "제76조제5항ㆍ제6항ㆍ제9항 및 제10항"
- 예: 제1항제2호에 따른 → "제1항제2호"

refs.law:
- 참조 대상이 다른 법령이면 해당 법령명
- 같은 법령 내부 참조이면 null
- 「」 안의 이름은 그 법령이다.
- "법"은 현재 법령의 모법(시행령·시행규칙이면 해당 법률), "영"은 해당 시행령, "같은 법"은 직전에 명시된 법령을 문맥에 따라 해석한다.
- 법령 표시(「」, 법, 영, 같은 법 등)가 붙지 않고 조문 번호만 나오면 현재 법령이다 → null
  단, 법령 표시와 조문 번호 사이에 괄호가 있으면 괄호를 건너뛰고 본다
  (예: 「소프트웨어 진흥법」(이하 "법"이라 한다) 제48조 → 소프트웨어 진흥법)

refs.follow:
- 해당 참조 조문을 다음 단계에서 계속 따라가야 하는지 여부
- 항상 true

refs.context:
- 해당 참조가 등장한 원문의 문장 또는 구절"""


def build_user_prompt(law: str, article: str, paragraph: str) -> str:
    return f"[법령명]\n{law}\n\n[조]\n{article}\n\n[항]\n{paragraph}"


# 조문 참조가 아닌 것: 원문에서 expression 바로 앞 글자로 판단
BYEOLJI = re.compile(r"별지\s*$")                                   # 별지 서식 번호
BUCHIK = re.compile(r"부칙\s*<?\s*$")                               # 부칙 조문·부칙 번호
PROMULGATION = re.compile(r"(대통령령|법률|총리령|부령|훈령|예규|고시)\s*$")   # 공포 번호 (호만 있을 때)
HO_ONLY = re.compile(r"^제\s?[\d,\-]+\s?호$")


def not_article_ref(expression: str, paragraph: str) -> bool:
    """별지 서식·부칙·법령 공포 번호처럼 조문 참조가 아닌 expression이면 True."""
    if "서식" in expression:
        return True
    prefix, body = ref_parse.split_prefix(expression)
    pos = paragraph.find(expression)
    before = (paragraph[max(0, pos - 10):pos] if pos >= 0 else "") + prefix   # 원문 앞 글자 + 표현에 포함된 표시
    if BYEOLJI.search(before) or BUCHIK.search(before):
        return True
    return bool(PROMULGATION.search(before) and HO_ONLY.match(body))


SAME_REF = re.compile(r"\s*(같은\s?조|같은\s?항|동\s?조|동\s?항)")


def assemble(law: str, article: str, paragraph: str, llm_out: dict) -> dict:
    """LLM 출력 + 파서 결과 → 최종 결과(ref_schema.json)."""
    current = re.match(r"제\d+조(?:의\d+)?", article).group()
    # 원문 위치 순서로 정렬 — "같은 조/항"이 원문에서 바로 앞의 참조를 따라가도록
    located = []
    for i, r in enumerate(llm_out["refs"]):
        if not_article_ref(r["expression"], paragraph):
            continue                          # 별지 서식·부칙·공포 번호는 조문 참조가 아님
        pos = paragraph.find(r["expression"])
        if pos < 0:
            log_fail.append(f"[원문에 없음] {r['expression']}")
            pos = len(paragraph) + i          # 못 찾으면 LLM 순서대로 뒤에 둠
        located.append((pos, r))
    located.sort(key=lambda x: x[0])

    refs, seen, prev, prev_law = [], set(), None, None
    for _, r in located:
        ref_law = r["law"].strip().strip("「」") if r["law"] else None   # 「」까지 적은 경우 정리
        prefix, body = ref_parse.split_prefix(r["expression"])
        if prefix in ABBREV.get(law, {}):
            ref_law = ABBREV[law][prefix]     # 문서에 정의된 약칭 → 정식 이름 (LLM 판단 무시)
        if ref_law is not None and ref_law.replace(" ", "") == law.replace(" ", ""):
            ref_law = None                    # 자기 법령을 이름으로 적은 경우 → null로 통일
        if not prefix:
            ref_law = None                    # 법령 표시 없이 번호만 → 현재 법령 (LLM 판단 무시)
        if SAME_REF.match(body):
            if prev is None:
                log_fail.append(f"[앞 참조 없음] {r['expression']}")
            else:
                ref_law = prev_law            # 같은 조/항은 법령도 앞 참조를 따름 (LLM 판단 무시)
        parsed, ok = ref_parse.parse(r["expression"], current, prev)
        if not ok:
            log_fail.append(r["expression"])
        for ref_article, paras in parsed:
            key = (ref_law, ref_article, tuple(paras))
            prev, prev_law = (ref_article, paras), ref_law
            if key in seen:                   # 법령·조·항이 모두 같으면 한 번만
                continue
            seen.add(key)
            refs.append({"expression": r["expression"], "article": ref_article, "paragraphs": paras,
                         "law": ref_law, "follow": r["follow"], "context": r["context"]})
    return {"article": current, "article_title": article,
            "law": law, "paragraph": ord(paragraph.lstrip()[0]) - ord("①") + 1, "refs": refs}


log_fail: list = []                           # 파서가 처리하지 못한 expression


def main() -> None:
    if not os.path.isdir(MODEL_DIR):          # 로컬 경로가 없으면 HF 다운로드로 넘어가지 않도록 즉시 중단
        raise SystemExit(f"모델 디렉터리 없음: {MODEL_DIR}")
    t0 = time.time()
    llm = LLM(model=MODEL_DIR, tokenizer=MODEL_DIR, max_model_len=MAX_MODEL_LEN,
              gpu_memory_utilization=0.92, seed=SEED, dtype="auto", quantization=QUANT or None)
    sp = SamplingParams(temperature=0.0, max_tokens=MAX_TOKENS, seed=SEED,
                        structured_outputs=StructuredOutputsParams(json=LLM_SCHEMA))
    load_s = time.time() - t0

    t1 = time.time()
    batch = [[{"role": "system", "content": SYSTEM_PROMPT},
              {"role": "user", "content": build_user_prompt(*c)}] for c in CASES]
    outs = [r.outputs[0] for r in llm.chat(batch, sampling_params=sp, use_tqdm=False)]
    infer_s = time.time() - t1

    header = (f"model={MODEL_DIR} quant={QUANT} load={load_s:.1f}s infer={infer_s:.1f}s "
              f"n={len(CASES)}\n")
    sections = []
    for i, (case, out) in enumerate(zip(CASES, outs), 1):
        law, article, para = case
        try:
            final = assemble(law, article, para, json.loads(out.text))
            jsonschema.validate(final, FINAL_SCHEMA)
            body = json.dumps(final, ensure_ascii=False, indent=2)
        except (json.JSONDecodeError, jsonschema.ValidationError) as e:
            body = f"[실패] {e}\n{out.text}"   # 토큰 한도로 잘리거나 최종 스키마 위반 시 LLM 원문 저장
        sections.append(f"===== [{i}] {law} {article} {para.splitlines()[0][:30]} =====\n"
                        f"out_tokens={len(out.token_ids)} finish={out.finish_reason}\n"
                        f"llm={out.text}\n{body}\n")
    if log_fail:
        sections.append("===== 파서 실패 expression =====\n" + "\n".join(log_fail) + "\n")
    text = header + "\n" + "\n".join(sections)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write(text)
    print(text)
    print(f"\n저장: {OUT_PATH}")


